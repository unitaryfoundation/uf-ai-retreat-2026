#!/usr/bin/env python3
"""Regenerate every INDEX.md from entry front matter. Never edit INDEX.md by hand.

Run: python3 scripts/build_index.py
"""
from retreat_lib import ROOT, entries, parse

HEADER = "<!-- GENERATED by scripts/build_index.py. Do not edit; edit the entries instead. -->\n\n"


def cell(value):
    return str(value or "").replace("|", "\\|").replace("\n", " ")


def table(columns, rows):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def write(rel, title, intro, body):
    (ROOT / rel).write_text(f"{HEADER}# {title}\n\n{intro}\n\n{body}", encoding="utf-8")


def link(path, label):
    return f"[{label}]({path.name})"


def main():
    rows = []
    for path in entries("attendees"):
        meta, _ = parse(path)
        meta = meta or {}
        rows.append([link(path, meta.get("name", path.stem)), meta.get("affiliation"), meta.get("background"),
                     meta.get("github") and f"@{meta['github']}"])
    write("attendees/INDEX.md", "Attendees", f"{len(rows)} people.",
          table(["Name", "Affiliation", "Background", "GitHub"], rows))

    for folder, title, who in [("charts/problems", "Problems worth 10x", "proposer"),
                               ("charts/structures", "Structures we'd want", "proposer")]:
        rows = []
        for path in entries(folder):
            meta, _ = parse(path)
            meta = meta or {}
            rows.append([link(path, meta.get("title", path.stem)), meta.get(who), meta.get("verifier"),
                         meta.get("status"), meta.get("group")])
        write(f"{folder}/INDEX.md", title, f"{len(rows)} entries.",
              table(["Entry", "Proposer", "Verifier", "Status", "Group"], rows))

    rows = []
    for path in entries("charts/tools"):
        meta, _ = parse(path)
        meta = meta or {}
        rows.append([link(path, meta.get("title", path.stem)), meta.get("contributor"), meta.get("used_for"),
                     meta.get("link")])
    write("charts/tools/INDEX.md", "Tools and tricks", f"{len(rows)} entries.",
          table(["Entry", "Contributor", "Used for", "Link"], rows))

    rows = []
    for path in entries("sessions/sat-failure-autopsies"):
        meta, _ = parse(path)
        meta = meta or {}
        anonymous = str(meta.get("anonymous", "")).lower() == "true"
        rows.append([link(path, meta.get("title", path.stem)), "anonymous" if anonymous else meta.get("author"),
                     meta.get("caught_by")])
    write("sessions/sat-failure-autopsies/INDEX.md", "Failure autopsies", f"{len(rows)} entries.",
          table(["Autopsy", "Who", "How it was caught"], rows))

    rows = []
    for readme in sorted((ROOT / "toolbox").glob("*/*/README.md")):
        summary = next((l.strip() for l in readme.read_text(encoding="utf-8").splitlines()
                        if l.strip() and not l.startswith("#")), "")
        rel = readme.parent.relative_to(ROOT / "toolbox")
        rows.append([f"[{rel.name}]({rel.as_posix()}/)", rel.parts[0], summary])
    write("toolbox/INDEX.md", "Toolbox", f"{len(rows)} reusable things.",
          table(["Thing", "Owner", "What it is"], rows))

    rows = []
    for readme in sorted((ROOT / "groups").glob("*/README.md")):
        meta, _ = parse(readme)
        meta = meta or {}
        rows.append([f"[{meta.get('title', readme.parent.name)}]({readme.parent.name}/)", meta.get("members"),
                     meta.get("verifier"), meta.get("scribe")])
    write("groups/INDEX.md", "Working groups", f"{len(rows)} groups.",
          table(["Group", "Members", "Verifier", "Scribe"], rows))
    print("indexes rebuilt")


if __name__ == "__main__":
    main()
